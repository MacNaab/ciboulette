/**
 * Helper to translate category enum to current language.
 */
export function getCategoryLabel(category: RecipeCategory | 'all', lang: SupportedLanguage): string {
  const key = `cat.${category}`;
  return TRANSLATIONS[lang]?.[key] || category;
}

/**
 * Helper to translate difficulty enum to current language.
 */
export function getDifficultyLabel(diff: Difficulty, lang: SupportedLanguage): string {
  const key = `diff.${diff}`;
  return TRANSLATIONS[lang]?.[key] || diff;
}
